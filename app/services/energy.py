"""Operational energy engine.

Primary path: build an IDF from the building parameters and run a real
EnergyPlus simulation (`energyplus` CLI, installed in the Docker image),
then read end-use totals from the tabular CSV output.

Fallback path: a deterministic ISO 13790-style monthly quasi-steady-state
model, so the dashboard always has heating / cooling / lighting numbers.
"""
from __future__ import annotations

import csv
import math
import os
import shutil
import subprocess
import tempfile
from typing import Any

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

# climate zone -> (heating degree days, cooling degree days, avg daily solar kWh/m2)
CLIMATES: dict[str, tuple[float, float, float]] = {
    "arctic": (6000, 50, 1.8),
    "cold": (4200, 300, 2.6),
    "temperate": (2400, 700, 3.2),
    "mediterranean": (1400, 1200, 4.4),
    "hot-dry": (600, 2600, 5.6),
    "hot-humid": (300, 3000, 4.8),
    "tropical": (100, 3200, 4.9),
}

# building type -> (lighting W/m2, equipment W/m2, operating hours per year)
BUILDING_TYPES: dict[str, tuple[float, float, float]] = {
    "office": (9.0, 12.0, 2600),
    "residential": (5.0, 6.0, 5200),
    "retail": (14.0, 8.0, 3600),
    "school": (10.0, 7.0, 2000),
    "hospital": (12.0, 20.0, 8760),
    "industrial": (8.0, 25.0, 4000),
}

DEFAULT_GRID_FACTOR = 0.233  # kgCO2e / kWh


def _profile(climate_zone: str | None, building_type: str | None):
    cz = (climate_zone or "temperate").strip().lower()
    bt = (building_type or "office").strip().lower()
    return CLIMATES.get(cz, CLIMATES["temperate"]), BUILDING_TYPES.get(bt, BUILDING_TYPES["office"])


def energyplus_available() -> bool:
    return shutil.which("energyplus") is not None


